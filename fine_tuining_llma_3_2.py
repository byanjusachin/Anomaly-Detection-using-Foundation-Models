# Convert each row into a conversation dict
def row_to_conversation(row):
    features = "\n".join([f"{col}: {row[col]}" for col in df.columns if col not in ["Class"]])
    label = "Yes" if row["Class"] == 1 else "No"
    return {
        "conversations": [
            {
                "role": "user",
                "content": f"Here is a credit card transaction:\n{features}\nIs this fraud?"
            },
            {
                "role": "assistant",
                "content": label
            }
        ]
    }

